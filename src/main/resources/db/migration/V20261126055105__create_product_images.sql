CREATE TABLE public.product_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variant_id BIGINT NOT NULL,
    image_url VARCHAR(2048) NOT NULL,
    sort_order INTEGER NOT NULL,

    CONSTRAINT fk_product_images_variant
        FOREIGN KEY (variant_id)
        REFERENCES public.product_variants(id)
        ON DELETE CASCADE,

    CONSTRAINT chk_product_images_sort_order
        CHECK (sort_order BETWEEN 0 AND 4),

    CONSTRAINT uq_product_images_variant_sort
        UNIQUE (variant_id, sort_order)
);

-- Migrate existing product images
INSERT INTO public.product_images (
    variant_id,
    image_url,
    sort_order
)
SELECT
    id,
    product_image_url,
    0
FROM public.product_variants
WHERE product_image_url IS NOT NULL
  AND TRIM(product_image_url) <> '';